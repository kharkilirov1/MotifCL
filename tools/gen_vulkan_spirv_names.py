#!/usr/bin/env python3
"""Generate src/runtime/vulkan_spirv_names.inc from the embedded SPIR-V header.

The Vulkan runtime's opt-in per-kernel GPU profiler (MOTIFCL_VK_PROFILE=1)
attributes timestamp deltas to kernels by SPIR-V module pointer identity, so it
needs a pointer -> source-kernel-name table. That table is derived mechanically
from the symbols in vulkan_spirv_kernels.inc; this script keeps it in sync.

Run after tools/gen_vulkan_spirv.py:

    python tools/gen_vulkan_spirv_names.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KERNELS = os.path.join(ROOT, "src", "runtime", "vulkan_spirv_kernels.inc")
OUTPUT = os.path.join(ROOT, "src", "runtime", "vulkan_spirv_names.inc")

SYMBOL = re.compile(r"inline constexpr std::uint32_t (k_[A-Za-z0-9_]+)\[\]")


def main():
    # The generated header is UTF-8, but older revisions were written with the
    # platform locale; tolerate stray bytes so the name table can always be
    # regenerated from a stale checkout.
    with open(KERNELS, "r", encoding="utf-8", errors="replace") as handle:
        text = handle.read()
    names = SYMBOL.findall(text)
    if not names:
        raise SystemExit(f"no kernel symbols found in {KERNELS}")
    lines = [
        "// Generated by tools/gen_vulkan_spirv_names.py — do not edit by hand.",
        "// Maps each embedded SPIR-V module pointer to its source kernel name so the",
        "// opt-in MOTIFCL_VK_PROFILE per-kernel GPU timer can report real kernel names.",
    ]
    for symbol in names:
        lines.append(f'    {{ vkspirv::{symbol}, "{symbol[2:]}" }},')
    with open(OUTPUT, "w", newline="\n", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)} ({len(names)} kernel names)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
